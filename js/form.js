/* =========================================
   ESCAPE HTML
========================================= */

function escapeFormHTML(text) {

    return String(text || "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");

}


/* =========================================
   RENDER FORMS
========================================= */

function renderForms(formArray) {

    const formsGrid =
        document.getElementById("formsGrid");

    if (!formsGrid) {
        return;
    }

    formsGrid.innerHTML = "";


    if (formArray.length === 0) {

        formsGrid.innerHTML = `
            <div class="forms-empty">

                <h2>कोई Form नहीं मिला</h2>

                <p>
                    Search बदलकर दोबारा कोशिश करें।
                </p>

            </div>
        `;

        return;
    }


    formArray.forEach(function (form) {

        const card =
            document.createElement("article");

        card.className = "form-card";


        card.innerHTML = `

            <div class="form-icon">
                📄
            </div>

            <span class="form-category">
                ${escapeFormHTML(form.category)}
            </span>

            <h3>
                ${escapeFormHTML(form.name)}
            </h3>

            <p>
                ${escapeFormHTML(form.description)}
            </p>

            <div class="form-actions">

                <a
                    href="${escapeFormHTML(form.file)}"
                    class="btn btn-dark"
                    target="_blank"
                    rel="noopener noreferrer"
                >
                    View Form
                </a>

                <a
                    href="${escapeFormHTML(form.file)}"
                    class="btn btn-outline"
                    download
                >
                    Download
                </a>

            </div>

        `;

        formsGrid.appendChild(card);

    });

}


/* =========================================
   FILTER FORMS
========================================= */

function filterForms() {

    const searchInput =
        document.getElementById("formSearch");

    const categorySelect =
        document.getElementById("formCategory");


    const query =
        searchInput
            ? searchInput.value
                .toLowerCase()
                .trim()
            : "";


    const category =
        categorySelect
            ? categorySelect.value
            : "";


    const filtered =
        formsData.filter(function (form) {

            const searchableText = [

                form.name,
                form.englishName,
                form.category,
                form.description

            ]
                .join(" ")
                .toLowerCase();


            const matchesSearch =
                !query ||
                searchableText.includes(query);


            const matchesCategory =
                !category ||
                form.category === category;


            return (
                matchesSearch &&
                matchesCategory
            );

        });


    renderForms(filtered);

}


/* =========================================
   INITIALIZE
========================================= */

document.addEventListener(
    "DOMContentLoaded",
    function () {

        renderForms(formsData);


        const searchInput =
            document.getElementById("formSearch");


        const categorySelect =
            document.getElementById("formCategory");


        if (searchInput) {

            searchInput.addEventListener(
                "input",
                filterForms
            );

        }


        if (categorySelect) {

            categorySelect.addEventListener(
                "change",
                filterForms
            );

        }

    }
);
